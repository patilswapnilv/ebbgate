import { envKeyForNodeToken } from "./secrets.js";

export type Tier = "private" | "internal" | "public";

export interface InitAnswers {
  publicUrl: string;
  dispatcherPort: number;
  /** `runner` defaults to http://<id>:8787. */
  nodes: Array<{ id: string; prefer?: boolean; runner?: string }>;
  /** Omit to keep all work on your machines (the secure default). */
  cloudRunner?: string;
  paperclipApiUrl: string;
  ollamaUrl: string;
  litellmUrl: string;
  agents: Array<{ id: string; tier: Tier }>;
  includeNotifyPlaceholders: boolean;
}

export function renderEbbgateYaml(a: InitAnswers): string {
  const preferId = a.nodes.find((n) => n.prefer)?.id ?? a.nodes[0]?.id;
  const nodeLines = a.nodes
    .map((n) => {
      const prefer = n.id === preferId ? ", prefer: true" : "";
      const runner = n.runner ?? `http://${n.id}:8787`;
      return `  ${n.id}: { runner: ${runner}, token: "\${${envKeyForNodeToken(n.id)}}"${prefer} }`;
    })
    .join("\n");

  const agentLines =
    a.agents.length === 0
      ? `  {} # none yet: unknown agents are treated as private. Add e.g.\n  # agent_research: { tier: public }`
      : a.agents.map((ag) => `  ${ag.id}: { tier: ${ag.tier} }`).join("\n");

  const notify = a.includeNotifyPlaceholders
    ? `
# Optional notifications — uncomment and fill env vars:
# notify:
#   telegram: { botToken: "\${TG_BOT_TOKEN}", chatId: "\${TG_CHAT_ID}" }
#   webhook: { url: "\${EG_NOTIFY_WEBHOOK}" }
`
    : "";

  const cloud = a.cloudRunner
    ? `
cloud:
  # TODO(verify-paperclip): confirm OpenClaw / cloud runtime path
  runner: ${a.cloudRunner}
`
    : `
# No cloud runner: nothing leaves your machines. Work waits ("defer") until a
# local node can take it. To let non-private work spill over, add:
# cloud:
#   runner: https://your-cloud-runner.example/paperclip
`;

  // Without a cloud runner every rule stays local or waits.
  const spill = a.cloudRunner ? "cloud" : "local-low";
  const away = a.cloudRunner ? "cloud" : "defer";

  return `# Generated by \`ebbgate init\`. Rules are first-match.
# Private tasks can never be routed to the cloud (rejected at startup).
# Agents not listed under \`agents\` are treated as private.

server:
  port: ${a.dispatcherPort}
  ${bindHostLine(a.publicUrl)}
  publicUrl: ${a.publicUrl}
  maxBodyBytes: 1048576

nodes:
${nodeLines}
${cloud}
paperclip:
  apiUrl: ${a.paperclipApiUrl}
  apiKey: "\${PAPERCLIP_API_KEY}"
  sharedSecret: "\${EG_PAPERCLIP_SECRET}"
  labelDeferred: false

agents:
${agentLines}

policies:
  - match: { label: local-files }
    available: local
    busy: local-low
    offline: defer
    notify: true
  - match: { tier: private }
    available: local
    busy: local-low
    offline: defer
  - match: { tier: internal }
    available: local
    busy: ${spill}
    offline: ${away}
  - default:
      available: ${a.cloudRunner ? "cloud" : "local"}
      busy: ${spill}
      offline: ${away}

presence:
  offlineAfterSeconds: 90
  drainConcurrency: 2
  deferredMaxAgeHours: 72
${notify}`;
}

/**
 * Bind address for the generated config. A loopback publicUrl keeps the
 * dispatcher on 127.0.0.1; any other publicUrl must be reachable by the nodes,
 * so the dispatcher listens on every interface (restrict with a firewall/VPN).
 */
export function bindHostLine(publicUrl: string): string {
  let hostname = "";
  try {
    hostname = new URL(publicUrl).hostname;
  } catch {
    // invalid URLs are reported by loadConfig
  }
  const loopback = hostname === "localhost" || hostname === "[::1]" || hostname.startsWith("127.");
  return loopback
    ? "host: 127.0.0.1 # publicUrl is local-only"
    : "host: 0.0.0.0 # nodes must reach publicUrl; restrict access with a firewall or VPN";
}
