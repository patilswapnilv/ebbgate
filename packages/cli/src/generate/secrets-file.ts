import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { parseEnvFile } from "@ebbgate/agent";

/** Name of the secrets file `ebbgate init` writes next to ebbgate.yaml. */
export const SECRETS_FILE = ".env";

/**
 * Show enough of a secret to recognise it, never enough to use it:
 * the first four characters and the length.
 */
export function maskSecret(value: string): string {
  if (value.length <= 8) return "****";
  return `${value.slice(0, 4)}… (${value.length} chars)`;
}

/** Read existing values, so `init --force` keeps tokens nodes already use. */
export function readExistingSecrets(path: string): Record<string, string> {
  if (!existsSync(path)) return {};
  try {
    return parseEnvFile(readFileSync(path, "utf8"));
  } catch {
    return {};
  }
}

/**
 * Write the secrets file with mode 0600. `writeFileSync`'s mode only applies when
 * the file is created, so the mode is set again for an existing file.
 */
export function writeSecretsFile(path: string, body: string): void {
  writeFileSync(path, body.endsWith("\n") ? body : `${body}\n`, { encoding: "utf8", mode: 0o600 });
  chmodSync(path, 0o600);
}

export function renderSecretsFile(vars: {
  sharedSecret: string;
  nodeTokens: Record<string, string>;
  paperclipApiKey?: string;
}): string {
  const nodeLines = Object.entries(vars.nodeTokens)
    .map(([k, v]) => `${k}=${v}`)
    .join("\n");
  const apiKey = vars.paperclipApiKey
    ? `PAPERCLIP_API_KEY=${vars.paperclipApiKey}`
    : "# Paperclip → Settings → API keys. `ebbgate doctor` reports it until it is set.\n# PAPERCLIP_API_KEY=";
  return `# Generated by \`ebbgate init\`. Secrets: keep this file mode 600 and out of git.
# Each Mac node needs only its own EG_NODE_<ID>_TOKEN line.

# Paperclip's http adapter sends this as "Authorization: Bearer <value>".
EG_PAPERCLIP_SECRET=${vars.sharedSecret}

${nodeLines}

${apiKey}
`;
}
